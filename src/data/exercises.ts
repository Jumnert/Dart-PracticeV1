export type Exercise = ExerciseMeta & {
  solution: string;
  expectedOutput: string;
  starter: string;
  outputLines: number;
};

export const exercises: Exercise[] = meta.map((item) => {
  const generated = solutions[item.id];
  return {
    ...item,
    solution: generated.solution,
    expectedOutput: generated.expectedOutput,
    starter: generated.starter,
    outputLines: generated.expectedOutput.split("\n").length,
  };
});

export const exerciseById = new Map(exercises.map((item) => [item.id, item]));

export function exercisesByCategory(category: CategoryId): Exercise[] {
  return exercises.filter((item) => item.category === category);
}

export function categoryOf(id: CategoryId): Category {
  return categories.find((item) => item.id === id) ?? categories[0];
}

